# Aula 9 - Operadores Aritméticos

adicao = 10 + 1.5
print('Adição =', adicao)

subtracao = 10 - 5
print('Subtração =', subtracao)

multiplicacao = 10 * 5
print('Multiplicação =', multiplicacao)

divisao = 100 / 35 # exibe o resultado da divisão com casas decimais Float
print('Divisão =', divisao)

divisao_inteira = 100 // 35 # Exibe apenas a parte inteira da divisão Int
print('Divisão Inteira =', divisao_inteira)

exponenciacao = 10 ** 2
print('Exponenciação =', exponenciacao)

modulo = 55 % 2 # resto da divisão
print('Módulo =', modulo)

print(10 % 5 == 0) # verifica se o resto da divisão é igual a 0, ou seja, se é par