#tipo de dado bool (boolean)
#ao questionar algo em um programa, 
#só existem duas respostas possiveis;
#sim (true) ou não (false)
#existem vários operadores para "questionar"
#Dentr eles o ==, que é um operador lógico
#questiona se um valor é igual o outro.
#True sempre maisculo e False também, caso contrário o Python não vai entender.
print(10 == 10) # True
print(10 == 11) # False
